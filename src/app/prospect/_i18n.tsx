export const messages = { es, en };
export type Messages = typeof es;

const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: Messages }>({
  lang: "en",
  setLang: () => {},
  t: en,
});

export function LangProvider({ initialLang, children }: { initialLang: Lang; children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const setLang = (l: Lang) => {
    setLangState(l);
    document.cookie = `prospect_lang=${l}; path=/; max-age=${60 * 60 * 24 * 365}`;
  };
  return <LangContext.Provider value={{ lang, setLang, t: messages[lang] }}>{children}</LangContext.Provider>;
}

export function useLang() {
  return useContext(LangContext);
}
